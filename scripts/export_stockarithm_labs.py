def _scan_for_secrets(repo_dir: Path) -> None:
    hits: list[str] = []
    for path in repo_dir.rglob("*"):
        if not path.is_file() or ".git" in path.parts:
            continue
        try:
            text = path.read_text(errors="ignore")
        except Exception:
            continue
        for pattern in SECRET_DENYLIST:
            if pattern.search(text):
                hits.append(str(path.relative_to(repo_dir)))
                break
    if hits:
        raise SystemExit("secret scan failed: " + ", ".join(sorted(hits)))


def _git(repo_dir: Path, args: list[str]) -> None:
    subprocess.run(["git", *args], cwd=repo_dir, check=True)


def export(repo_dir: Path, push: bool = False, remote_url: str | None = None) -> None:
    repo_dir.mkdir(parents=True, exist_ok=True)
    for name in ["stockarithm_labs", "schemas", "samples", "examples", "docs"]:
        path = repo_dir / name
        if path.exists():
            shutil.rmtree(path)

    _write_package(repo_dir)
    _write_router(repo_dir)
    _write_schemas(repo_dir)
    _write_samples(repo_dir)
    _write_examples(repo_dir)
    _write_docs(repo_dir)
    _scan_for_secrets(repo_dir)

    if not (repo_dir / ".git").exists():
        _git(repo_dir, ["init"])
        _git(repo_dir, ["symbolic-ref", "HEAD", "refs/heads/main"])
    if remote_url:
        remotes = subprocess.check_output(["git", "remote"], cwd=repo_dir, text=True).splitlines()
        if "origin" in remotes:
            _git(repo_dir, ["remote", "set-url", "origin", remote_url])
        else:
            _git(repo_dir, ["remote", "add", "origin", remote_url])
    _git(repo_dir, ["add", "."])
    status = subprocess.check_output(["git", "status", "--porcelain"], cwd=repo_dir, text=True).strip()
    if status:
        _git(repo_dir, ["config", "user.name", "stockarithm-labs-bot"])
        _git(repo_dir, ["config", "user.email", "stockarithm-labs-bot@users.noreply.github.com"])
        _git(repo_dir, ["commit", "-m", f"sync public adapter lab {datetime.now(timezone.utc).strftime('%Y-%m-%d')}"])
    if push:
        _git(repo_dir, ["push", "-u", "origin", "main"])


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--repo-dir", default=str(DEFAULT_REPO_DIR))
    parser.add_argument("--remote-url", default="")
    parser.add_argument("--push", action="store_true")
    args = parser.parse_args()
    export(Path(args.repo_dir).expanduser(), push=args.push, remote_url=args.remote_url or None)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
