def _write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)


def _copy_adapter(src_name: str, repo_dir: Path) -> None:
    src = ROOT / "crazy" / "adapters" / src_name
    text = src.read_text()
    text = text.replace("from crazy.config import CRAZY_CACHE_DIR\n", "from stockarithm_labs.cache import DEFAULT_CACHE_DIR\n")
    text = text.replace("from crazy.utils import cached_fetch\n", "from stockarithm_labs.cache import cached_fetch\n")
    text = text.replace("CRAZY_CACHE_DIR", "DEFAULT_CACHE_DIR")
    dst = repo_dir / "stockarithm_labs" / "adapters" / src_name
    _write(dst, f"{GENERATED_MARKER}\n{text}")


